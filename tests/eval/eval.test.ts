/**
 * SetSense AI eval harness runner.
 *
 * Runs every encoded prompt from setsense_ai_eval_matrix.md through the headless
 * engine driver and scores it against its "Pass when" predicate. Writes a
 * scorecard (tests/eval/scorecard.md) on every run.
 *
 * This test does NOT fail the suite on a low pass-rate — the pass-rate is a
 * measurement we drive up across phases. It only fails if the harness itself
 * breaks (a case throws, or no cases ran). Set EVAL_STRICT=1 to also fail when
 * any case regresses below the recorded baseline.
 */
import { describe, expect, it } from 'vitest'
import { writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { buildWorld } from './fixtures'
import { resolveQuery } from './driver'
import { ALL_CASES } from './cases'
import type { CheckResult, Complexity } from './types'

interface Row {
  id: string
  category: string
  complexity: Complexity
  type: string
  pass: boolean
  reason: string
}

function run(): Row[] {
  const ctx = buildWorld()
  return ALL_CASES.map((c) => {
    let pass = false
    let reason = ''
    try {
      const result = resolveQuery(c.prompt, ctx)
      const verdict: CheckResult = c.check(result, ctx)
      pass = verdict === true
      reason = verdict === true ? '' : verdict
    } catch (err) {
      pass = false
      reason = `threw: ${(err as Error).message}`
    }
    return {
      id: c.id,
      category: c.category,
      complexity: c.complexity,
      type: c.type,
      pass,
      reason
    }
  })
}

function pct(n: number, d: number): string {
  return d === 0 ? '—' : `${Math.round((n / d) * 100)}%`
}

function groupBy<T, K extends string>(rows: T[], key: (r: T) => K): Map<K, T[]> {
  const m = new Map<K, T[]>()
  for (const r of rows) {
    const k = key(r)
    m.set(k, [...(m.get(k) ?? []), r])
  }
  return m
}

function scorecard(rows: Row[]): string {
  const total = rows.length
  const passed = rows.filter((r) => r.pass).length
  const lines: string[] = []
  lines.push('# SetSense AI Eval Scorecard')
  lines.push('')
  lines.push(
    `**Overall: ${passed}/${total} (${pct(passed, total)})** · ${ALL_CASES.length} encoded`
  )
  lines.push('')
  lines.push('> Generated by `tests/eval/eval.test.ts`. Model OFF (deterministic baseline path).')
  lines.push('')

  lines.push('## By category')
  lines.push('')
  lines.push('| Category | Pass | Rate |')
  lines.push('| --- | --- | --- |')
  for (const [cat, rs] of groupBy(rows, (r) => r.category)) {
    const p = rs.filter((r) => r.pass).length
    lines.push(`| ${cat} | ${p}/${rs.length} | ${pct(p, rs.length)} |`)
  }
  lines.push('')

  lines.push('## By complexity')
  lines.push('')
  lines.push('| Complexity | Pass | Rate |')
  lines.push('| --- | --- | --- |')
  for (const lvl of ['Beginner', 'Intermediate', 'Advanced', 'Expert'] as Complexity[]) {
    const rs = rows.filter((r) => r.complexity === lvl)
    if (rs.length === 0) continue
    const p = rs.filter((r) => r.pass).length
    lines.push(`| ${lvl} | ${p}/${rs.length} | ${pct(p, rs.length)} |`)
  }
  lines.push('')

  lines.push('## Failing cases')
  lines.push('')
  const fails = rows.filter((r) => !r.pass)
  if (fails.length === 0) {
    lines.push('_None 🎉_')
  } else {
    lines.push('| ID | Category | Reason |')
    lines.push('| --- | --- | --- |')
    for (const f of fails)
      lines.push(`| ${f.id} | ${f.category} | ${f.reason.replace(/\|/g, '\\|')} |`)
  }
  lines.push('')
  return lines.join('\n')
}

describe('SetSense AI eval matrix', () => {
  it('runs every encoded case and writes a scorecard', () => {
    const rows = run()
    const card = scorecard(rows)
    const out = fileURLToPath(new URL('./scorecard.md', import.meta.url))
    writeFileSync(out, card, 'utf8')

    const passed = rows.filter((r) => r.pass).length

    console.log(
      `\n[eval] ${passed}/${rows.length} (${pct(passed, rows.length)}) — scorecard → ${out}\n`
    )

    // Harness integrity: every case ran.
    expect(rows.length).toBe(ALL_CASES.length)
    expect(rows.length).toBeGreaterThan(0)

    if (process.env.EVAL_STRICT === '1') {
      const fails = rows.filter((r) => !r.pass)
      expect(fails, fails.map((f) => `${f.id}: ${f.reason}`).join('\n')).toHaveLength(0)
    }
  })
})
